const byVariant = new Map<string, CuratedTerm>();
const variantsLongestFirst: { variant: string; term: CuratedTerm }[] = [];
for (const t of CURATED_TERMS) {
  for (const v of t.variants) {
    if (byVariant.has(v)) throw new Error(`Duplicate curated term variant: ${v}`);
    byVariant.set(v, t);
    variantsLongestFirst.push({ variant: v, term: t });
  }
}
variantsLongestFirst.sort((a, b) => b.variant.length - a.variant.length);

/** The curated term a (lowercased) canonical/variant belongs to, if any. */
export function curatedTermFor(term: string): CuratedTerm | undefined {
  return byVariant.get(term.trim().toLowerCase());
}

/** Curated owner of an indexed regex match; longest variant always wins. */
export function curatedTermForMatch(match: string): CuratedTerm | undefined {
  const normalized = match.trim().toLowerCase().replace(/\s+/g, ' ');
  return variantsLongestFirst.find(({ variant }) => normalized.startsWith(variant))?.term;
}
